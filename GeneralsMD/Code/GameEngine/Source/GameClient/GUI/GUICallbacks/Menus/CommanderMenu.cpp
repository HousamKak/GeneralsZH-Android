// FILE: CommanderMenu.cpp /////////////////////////////////////////////////////////////////////////
// GeneralsX @feature ZH Commander 09/10/2026 The app's own settings, inside the game.
//
// Reached from the Options menu's ZH COMMANDER button (OptionsMenu.cpp). It shows the app
// version and offers what used to sit in the Android launcher: the simulation rate, the
// renderer, upscaling, interface and text size, the support report, the shell's remaining
// settings and a waiting update. Everything here is read when the game starts, so Apply saves
// and offers a restart. Settings in Options.ini are written by the engine itself; the ones the
// shell keeps (simulation rate, renderer) go through ZHCommander.h. A row whose platform does
// not have the setting is hidden. Layout: Window/Menus/CommanderMenu.wnd, generated by
// scripts/tooling/wnd/make-commander-menu.py.
///////////////////////////////////////////////////////////////////////////////////////////////////

